package com.libcryptsafe.media

/**
 * Словарь типов медиа-слоя.
 *
 * ВАЖНО про совместимость: поле "type" в проводе уже используется как СТРОКА
 * существующими модулями ("msg", "channel_post", "channel_fetch",
 * "prekeys_request", "GAME_MOVE" и т.д.). Поэтому каждый ContentType несёт свою
 * СТРОКОВУЮ метку (wire) и встаёт в тот же ряд равноправным соседом — числовой
 * enum создал бы два несовместимых мира в одном поле. Медиа-метки уникальны и
 * не пересекаются с существующими.
 *
 * Этот enum покрывает ТОЛЬКО медиа-слой (+ TEXT как якорь базового чата). Он
 * НЕ пытается втянуть game/channel-типы — те живут в своих модулях строками;
 * централизовать их здесь означало бы синхронизировать этот файл при каждом
 * изменении нард/каналов (против DRY). Медиа — равноправный сосед, не король.
 *
 * ЗАГЛУШКА-КАРКАС: значения объявлены, но "двигатель" ещё не подключён — ни
 * сети, ни UI, ни крипто. Их подключат следующие кирпичи (перенос
 * TransferManager -> крипто-слой -> сериализация -> транспорт -> UI).
 *
 * МАЯКИ на будущее (файлов пока НЕ создаём — интерфейс без потребителя = код,
 * который придётся переписать; появятся вместе с первым, кто их реализует):
 *   - MediaTransport   : отправка/приём чанков (ветка A = OnlineP2PTransport;
 *                        BlobTTLTransport = отложенный офлайн-режим).
 *   - TrafficShaper    : морфинг трафика против анализа (сейчас — не нужен;
 *                        сперва честно ответить "от кого защищаемся").
 *   - VoiceSession     : реалтайм-аудио/видео (Opus + jitter buffer + NAT);
 *                        отдельный большой проект. CALL_* ниже — зарезервированы
 *                        под него; попытка звонка сейчас = "будет в будущем".
 */
enum class ContentType(val wire: String) {
    // --- базовый чат (якорь совместимости) ---
    TEXT("msg"),

    // --- передача файла (фото/видео/файл), чанками ---
    MEDIA_INIT("media_init"),      // старт передачи: метаданные + эфемерный ключ
    MEDIA_CHUNK("media_chunk"),    // один кусок данных, seq
    MEDIA_DONE("media_done"),      // финализация передачи
    CONTROL("media_control"),      // служебное: добор пропущенных чанков {missing:[...]}

    // --- ЗАРЕЗЕРВИРОВАНО под VoiceSession (не реализовано) ---
    CALL_OFFER("call_offer"),
    CALL_ANSWER("call_answer"),
    CALL_END("call_end");

    companion object {
        /** Разобрать строковую метку из провода. null = неизвестный/чужой тип
         *  (game/channel/prekeys обрабатываются своими модулями — это норма). */
        fun fromWire(wire: String): ContentType? = values().firstOrNull { it.wire == wire }
    }
}
